//! `refield` adds **cross-type struct update syntax** and partial projection to Rust.
//!
//! Annotate a target struct with [`#[derive(Refield)]`](Refield) or [`#[refieldable]`](refieldable),
//! then construct it with [`refield!(Target { field: value, ..raw })`](refield) or directly with
//! its companion macro `Target! { field: value, ..raw }`. Fields that are not written explicitly
//! are taken by name from `raw`, which may be a value of an entirely different type. Automatic
//! extraction moves the source fields: neither the target nor the source needs `Clone`. Writing
//! the source first, as in `refield!(Target { make_raw().., field: value })`, reads it before the
//! explicit fields.
//!
//! - [Core concepts](#core-concepts)
//! - [Cross-type updates and partial moves](#cross-type-updates-and-partial-moves)
//! - [Field and struct attributes](#field-and-struct-attributes)
//! - [Evaluation order and temporaries](#evaluation-order-and-temporaries)
//! - [Struct shapes](#struct-shapes)
//! - [Generics, aliases, and `Self`](#generics-aliases-and-self)
//! - [Associated types](#associated-types)
//! - [Visibility, exports, and crate paths](#visibility-exports-and-crate-paths)
//! - [Limitations](#limitations)
//! - [Compatibility](#compatibility)
//!
//! ## Core concepts
//!
//! There are two spellings for the same operation:
//!
//! | Spelling | Resolution |
//! | --- | --- |
//! | `refield!(Target { ..raw })` | Builds the companion macro path from `Target` and calls it. |
//! | `Target! { ..raw }` | Calls the companion macro generated next to the struct. |
//!
//! The companion macro is a `macro_rules!` item generated by the derive and re-exported under the
//! struct's name, in the macro namespace. Importing the struct with `use path::Target;` imports the
//! companion macro as well; importing it with `use path::Target as Alias;` renames both.
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     host: &'static str,
//!     port: u16,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     host: String,
//!     port: u16,
//! }
//!
//! let raw = Raw { host: "localhost", port: 8080 };
//! // `host` is converted explicitly; `port` is moved from `raw` by name.
//! let config = refield!(Config { host: raw.host.to_owned(), ..raw });
//! assert_eq!(config, Config { host: "localhost".into(), port: 8080 });
//!
//! // The companion macro accepts the same body.
//! let raw = Raw { host: "example.com", port: 443 };
//! let config = Config! { host: raw.host.to_owned(), ..raw };
//! assert_eq!(config.port, 443);
//! ```
//!
//! The expansion is a plain struct literal plus, at most, a few `let` bindings. It performs no
//! allocation, needs no trait implementations, and therefore also works in `const fn`:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { port: u16 }
//!
//! #[derive(Refield)]
//! struct Config { port: u16 }
//!
//! const fn build(raw: Raw) -> Config {
//!     refield!(Config { ..raw })
//! }
//!
//! const CONFIG: Config = build(Raw { port: 8080 });
//! assert_eq!(CONFIG.port, 8080);
//! ```
//!
//! ## Cross-type updates and partial moves
//!
//! Native struct update syntax requires the source and the target to have the same type:
//!
//! ```compile_fail,E0308
//! struct Raw { port: u16 }
//! struct Config { port: u16 }
//!
//! let raw = Raw { port: 8080 };
//! let config = Config { ..raw }; // error: expected `Config`, found `Raw`
//! ```
//!
//! `refield!` lifts that restriction, and it does so without first converting `raw` as a whole.
//! Fields written explicitly are evaluated **before** `..raw` is consumed, so they may move,
//! borrow, or parse individual `raw` fields while the remaining fields are still moved
//! automatically. This is what makes fallible conversions natural:
//!
//! ```rust
//! use core::num::ParseIntError;
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     port: Option<&'static str>,
//!     host: &'static str,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     port: u16,
//!     #[refield(with = |host: &'static str| host.into())]
//!     host: String,
//! }
//!
//! impl TryFrom<Raw> for Config {
//!     type Error = ParseIntError;
//!
//!     fn try_from(raw: Raw) -> Result<Self, Self::Error> {
//!         Ok(refield!(Config {
//!             // `raw.port` is consumed here, before `..raw` moves `raw.host`.
//!             port: raw.port.unwrap_or("0").parse()?,
//!             ..raw
//!         }))
//!     }
//! }
//!
//! let config = Config::try_from(Raw { port: Some("8080"), host: "localhost" }).unwrap();
//! assert_eq!(config, Config { port: 8080, host: "localhost".into() });
//! assert!(Config::try_from(Raw { port: Some("nope"), host: "localhost" }).is_err());
//! ```
//!
//! The source does not need `Clone`, and fields may be moved out of it *before* the update. The
//! automatic extraction keeps working because it only moves the fields that are still present:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Token(String);
//!
//! struct Raw {
//!     id: Token,
//!     name: Token,
//!     payload: Token,
//! }
//!
//! #[derive(Refield)]
//! struct Parsed {
//!     id_len: usize,
//!     name: Token,
//!     payload: Token,
//! }
//!
//! let raw = Raw {
//!     id: Token("id-001".into()),
//!     name: Token("gateway".into()),
//!     payload: Token("body".into()),
//! };
//! let id = raw.id; // Move one field out before the update.
//! let parsed = refield!(Parsed {
//!     id_len: id.0.len() + raw.name.0.len(), // Borrow other fields while computing.
//!     ..raw
//! });
//! assert_eq!(parsed.id_len, 6 + 7);
//! assert_eq!(parsed.name.0, "gateway");
//! assert_eq!(parsed.payload.0, "body");
//! ```
//!
//! Source fields that the target does not declare are ignored. They are left in `raw` when `raw`
//! is a place, and dropped with the temporary otherwise.
//!
//! ## Field and struct attributes
//!
//! Attributes are written as `#[refield(...)]` on fields and on the struct, or as arguments to
//! [`#[refieldable]`](refieldable):
//!
//! | Attribute | Scope | Effect |
//! | --- | --- | --- |
//! | `name = "..."` | field, struct | Reads the automatic value from a differently named source field. `{}` expands to the target field's name. On a struct, applies to every automatic field. |
//! | `with = value` | field, struct | Converts the automatic value. Accepts a pseudo-closure (`\|pattern: Type\| body`) (use a typed parameter, e.g. `\|x: SrcType\|` ..., for heterogeneous source types). On a struct, applies to every automatic field. |
//! | `default` / `default = expr` | field | Fills an omitted or skipped field: initializes the field when there is no `..rest` or when marked `skip`. |
//! | `skip` | field | Never reads the field from `..rest`; initializes it from its default. Combine with `default = expr` to choose the value. |
//! | `bound(...)` | field | Adds `where` predicates to the generated helper method. Parentheses syntax only. |
//! | `const` | field, struct | Generates `const fn` helper methods. On a struct, applies to every helper. |
//! | `on(...)` | field | Declares a rule that only applies when the call selects one of those profiles with `@name` (e.g. `on(name)` or `on(first, second)`). Multiple attributes for the same profile merge. See [Profiles](#profiles-per-call-source-rules). |
//! | `crate = path` | struct | Redirects generated paths to a renamed or re-exported `refield` crate. |
//!
//! Attributes only apply to **automatically extracted** fields. A field written explicitly in the
//! `refield!` body is initialized with exactly the expression given, bypassing `with`, `default`,
//! and `skip`.
//!
//! An explicit field keeps its own `#[cfg(...)]` / `#[cfg_attr(..., cfg(...))]`: when the
//! condition is false the entry is stripped and the field is extracted automatically instead,
//! exactly like native struct update syntax.
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { value: u8, other: u8 }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Target { value: u8, other: u8 }
//!
//! let raw = Raw { value: 5, other: 0 };
//! let target = refield!(Target {
//!     #[cfg(all())]
//!     value: 10,
//!     #[cfg(any())]
//!     value: 20,
//!     other: 1,
//!     ..raw
//! });
//! assert_eq!(target, Target { value: 10, other: 1 });
//! ```
//!
//! `name` renames the **source** member. `{}` is replaced with the target member's name, so a
//! single pattern can describe a whole struct. This covers the common "prefixed raw fields"
//! layout when declared once on the struct instead of on every field:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     raw_port: u32,
//!     raw_name: String,
//! }
//!
//! // The struct-level `name` is applied to each field.
//! #[derive(Refield, Debug, PartialEq)]
//! #[refield(name = "raw_{}")]
//! struct Config {
//!     port: u32,
//!     name: String,
//! }
//!
//! let config = refield!(Config { ..Raw { raw_port: 8080, raw_name: "node".into() } });
//! assert_eq!(config, Config { port: 8080, name: "node".into() });
//! ```
//!
//! The same attributes can be written per field. A field-level `name`, `with`, or `skip`
//! **overrides** the struct-level default for that field:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     raw_port: u32,
//!     legacy_name: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! #[refield(name = "raw_{}")]
//! struct Config {
//!     port: u32,
//!     // Reads `legacy_name` instead of `raw_name`.
//!     #[refield(name = "legacy_name")]
//!     name: String,
//! }
//!
//! let config = refield!(Config { ..Raw { raw_port: 1, legacy_name: "old".into() } });
//! assert_eq!(config, Config { port: 1, name: "old".into() });
//! ```
//!
//! `with = value` calls a pseudo-closure shorthand for a helper method:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! fn title_case(value: &str) -> String {
//!     value
//!         .split_whitespace()
//!         .map(|word| {
//!             let mut chars = word.chars();
//!             chars.next().map(char::to_uppercase).into_iter().flatten().chain(chars).collect()
//!         })
//!         .collect::<Vec<String>>()
//!         .join(" ")
//! }
//!
//! struct Raw { label: &'static str }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     #[refield(with = |s: &str| title_case(s))]
//!     label: String,
//! }
//!
//! assert_eq!(
//!     refield!(Config { ..Raw { label: "hello world" } }).label,
//!     "Hello World",
//! );
//! ```
//!
//! The conversion input type is resolved in two ways:
//!
//! - **Homogeneous pseudo-closures** default to the target field's type, so
//!   an `i32` field can use `#[refield(with = |x| x + 1)]`
//!   without naming any type.
//! - **Heterogeneous conversions** specify the input type via a typed pseudo-closure parameter:
//!   `#[refield(with = |s: &str| title_case(s))]` or
//!   `#[refield(with = |raw: &'a [u8]| core::str::from_utf8(raw).unwrap())]`.
//!
//! When the source type differs from the target field type, the input type must be spelled out
//! on the pseudo-closure parameter because the custom conversion becomes an inherent helper
//! method on the target struct and cannot infer its parameter from the call site's source type.
//!
//! A struct-level `with` is compiled once per field. An untyped pseudo-closure
//! sees each field's own type, while a typed one specifies a shared input type
//! for every field:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { port: u16, retries: u16 }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! #[refield(with = |value: u16| u32::from(value) * 2)]
//! struct Config {
//!     port: u32,
//!     retries: u32,
//! }
//!
//! assert_eq!(
//!     refield!(Config { ..Raw { port: 4, retries: 5 } }),
//!     Config { port: 8, retries: 10 },
//! );
//! ```
//!
//! A pseudo-closure's explicit return type becomes the helper's return type, so a conversion that
//! produces a different type than the field is a compile error rather than being silently
//! discarded:
//!
//! ```compile_fail,E0308
//! use refield::{Refield, refield};
//! #[derive(Refield)]
//! struct Config {
//!     // The pseudo-closure returns `bool`, but the field is a `u8`.
//!     #[refield(with = |value: u8| -> bool { value != 0 })]
//!     port: u8,
//! }
//! struct Raw { port: u8 }
//! let config = refield!(Config { ..Raw { port: 1 } });
//! # let _ = config;
//! ```
//!
//! Unsupported closure forms and bare function paths are rejected where the value starts. Only a
//! pseudo-closure (`|pattern: Type| body`) is accepted after `with`.
//! `async`, `move`, `const`, and `for<...>` prefixes are ordinary syntax
//! errors, and so is a parenthesized form; there is no per-modifier
//! diagnostic:
//!
//! ```compile_fail
//! use refield::Refield;
//! #[derive(Refield)]
//! struct Config {
//!     #[refield(with = async |value: u8| value)]
//!     port: u8,
//! }
//! ```
//!
//! A pseudo-closure is a shorthand for a helper method, not full Rust closure
//! support: it may name its input with `_` to take the field's type, and a
//! nested placeholder such as `Vec<_>` reaches the helper signature and is
//! reported there by `rustc`.
//!
//! ```compile_fail,E0121
//! use refield::Refield;
//! #[derive(Refield)]
//! struct Config {
//!     #[refield(with = |value: Vec<_>| value.len())]
//!     port: usize,
//! }
//! ```
//!
//! ### Definition-site scope
//!
//! Every custom `with` conversion and `default = expr` is compiled into an inherent helper
//! method on the target struct instead of being pasted into the `refield!` call site. The
//! expression therefore evaluates in the struct's **definition-site scope**: it can name the
//! struct's generic parameters and lifetimes, private functions and constants of the defining
//! module, and paths that are not imported where `refield!` is written.
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! mod model {
//!     use refield::Refield;
//!
//!     // Private to `model`, yet usable from the conversion below.
//!     fn parse_port(text: &str) -> u16 {
//!         text.trim().parse().unwrap_or(8080)
//!     }
//!
//!     #[derive(Refield, Debug, PartialEq)]
//!     pub struct Config<T: Default> {
//!         pub port: u16,
//!         // `T::default()` resolves against the struct's own type parameter.
//!         #[refield(skip, default = T::default())]
//!         pub fallback: T,
//!         #[refield(with = |text: &str| parse_port(text))]
//!         pub raw_port_text: u16,
//!     }
//! }
//!
//! struct Raw { raw_port_text: &'static str }
//!
//! let raw = Raw { raw_port_text: " 9090 " };
//! let config = refield!(model::Config::<String> { port: 1, ..raw });
//! assert_eq!(config.port, 1);
//! assert_eq!(config.raw_port_text, 9090);
//! assert_eq!(config.fallback, String::new());
//! ```
//!
//! Because the helper is an ordinary method, its `where` clause can be extended per field with
//! `bound`, without constraining the struct itself:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config<T> {
//!     // `T` has no `Default` bound on the struct; only this helper requires it.
//!     #[refield(bound(T: Default), default = T::default())]
//!     fallback: T,
//! }
//!
//! assert_eq!(refield!(Config::<u32> {}), Config { fallback: 0 });
//! ```
//!
//! `bound(T: Trait)` adds predicates; repeat the key or separate predicates with commas to add
//! several. Parentheses syntax `bound(...)` is required.
//!
//! ### `const` helpers
//!
//! A custom conversion or default expression is not `const`-callable by default. Mark the field
//! with `#[refield(const, with = ...)]` or `#[refield(const, default = ...)]` to generate a
//! `const fn` helper, or mark the whole struct with `#[refield(const)]` (`#[refieldable(const)]`
//! when using the attribute macro) to promote every helper at once:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! const fn double(value: u16) -> u16 {
//!     value * 2
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! #[refield(const)]
//! struct Config {
//!     #[refield(with = |value| double(value))]
//!     doubled: u16,
//!     #[refield(skip, default = 60)]
//!     ttl: u16,
//! }
//!
//! struct Raw { doubled: u16 }
//!
//! const CONFIG: Config = refield!(Config { ..Raw { doubled: 21 } });
//! assert_eq!(CONFIG, Config { doubled: 42, ttl: 60 });
//! ```
//!
//! A pure literal default such as `default = 60` is turned into a `const fn` automatically, so
//! it needs no `const` flag. The flag is required when the expression calls something that is
//! not itself a literal.
//!
//! Combined with `name`, `with` expresses polarity inversion or any other
//! renamed-and-converted field:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { off: bool }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     #[refield(name = "off", with = |v| !v)]
//!     on: bool,
//! }
//!
//! assert!(!refield!(Config { ..Raw { off: true } }).on);
//! assert!(refield!(Config { ..Raw { off: false } }).on);
//! ```
//!
//! `default` fills a field when there is no source value:
//!
//! - **Without `..rest`**: unwritten fields are initialized from their defaults.
//! - **With `..rest` and `skip`**: the field is skipped during extraction and initialized from its default.
//!
//! Bare `default` means `Default::default()`; `default = expr` supplies any expression.
//! `skip` implies `default` and removes the field from extraction entirely, which is useful for
//! derived or cached values that the source never contains:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     ttl: u32,
//!     hosts: Vec<&'static str>,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     #[refield(default = 60)]
//!     ttl: u32,
//!     #[refield(skip, default)]
//!     retries: u32,
//!     #[refield(with = |hosts: Vec<&str>| hosts.into_iter().map(str::to_owned).collect())]
//!     hosts: Vec<String>,
//!     #[refield(skip, default = String::from("generated"))]
//!     tag: String,
//!     #[refield(skip)]
//!     hits: usize,
//! }
//!
//! let config = refield!(Config {
//!     ..Raw { ttl: 30, hosts: vec!["a", "b"] }
//! });
//! assert_eq!(config, Config {
//!     ttl: 30,
//!     retries: 0,
//!     hosts: vec!["a".into(), "b".into()],
//!     tag: "generated".into(),
//!     hits: 0,
//! });
//! ```
//!
//! Without `..rest`, defaults fill the fields that are not written. The remaining fields must
//! still be provided explicitly:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     host: String,
//!     #[refield(default = 8080)]
//!     port: u16,
//! }
//!
//! let config = refield!(Config { host: "localhost".into() });
//! assert_eq!(config, Config { host: "localhost".into(), port: 8080 });
//! ```
//!
//! `skip` may only be combined with `default`:
//!
//! ```compile_fail
//! use refield::Refield;
//! #[derive(Refield)]
//! struct Config {
//!     #[refield(skip, with = |value: u16| value)]
//!     port: u16,
//! }
//! ```
//!
//! ### Profiles: per-call-source rules
//!
//! One struct often has several raw counterparts — a fast path, a thorough path, a legacy
//! layout — that share the target type but name or transform fields differently. A field can
//! declare an extra rule per **profile** with `on(...)`, selected at the call site with `@name` as
//! the first entry of the body:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     host: String,
//!     fast_host: String,
//!     port: u16,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Config {
//!     #[refield(on(fast), name = "fast_host")]
//!     host: String,
//!     #[refield(on(fast), with = |port: u16| port / 2)]
//!     port: u16,
//! }
//!
//! let raw = || Raw { host: "default".into(), fast_host: "fast".into(), port: 100 };
//! // No profile: every field uses its default rule.
//! assert_eq!(
//!     refield!(Config { ..raw() }),
//!     Config { host: "default".into(), port: 100 },
//! );
//! // `@fast` selects the dedicated rule wherever one is declared.
//! assert_eq!(
//!     refield!(Config { @fast ..raw() }),
//!     Config { host: "fast".into(), port: 50 },
//! );
//! ```
//!
//! Attributes contribute configuration per profile. Attributes without `on(...)`
//! contribute to the field's default rule (several such attributes are merged). Similarly,
//! multiple attributes specifying `on(...)` for the same profile merge their configuration
//! keys. A field that does not declare a rule for the selected profile falls back to its
//! default rule, so a profile only needs to mention the fields it actually changes.
//! `on(...)` uses parentheses syntax and accepts one name or a list:
//!
//! - `#[refield(on(alt), name = "alt_host")]`
//! - `#[refield(on(alt, legacy), with = |v| normalize(v))]`
//!
//! A rule can bind several profiles at once, and a field may declare different rules for
//! different profiles; a profile with no rule of its own inherits the field's default rule.
//!
//! Multiple `#[refield(on(p), ...)]` attributes for the same profile `p` merge keys across
//! attributes, but specifying conflicting or duplicate keys (such as multiple `name = ...` on the
//! same profile) is an error. Selecting a profile the schema never mentions is rejected at the call
//! site:
//!
//! ```compile_fail
//! use refield::{Refield, refield};
//! #[derive(Refield)]
//! struct Config {
//!     #[refield(on(fast))]
//!     port: u16,
//! }
//! # struct Raw { port: u16 }
//! # let raw = Raw { port: 1 };
//! let _ = refield!(Config { @thorough ..raw });
//! ```
//!
//! The selector is written `@name` and must be the first entry of the body. The comma after it is
//! optional: `{ @alt ..raw }`, `{ @alt, ..raw }`, `{ @alt field: 1, ..raw }`, `{ @alt raw.. }`,
//! and `{ @alt }` are all accepted. Selecting a profile switches the `default` strategy only for fields that declare
//! a rule for it; every other field keeps its default rule, exactly as without a selector.
//!
//! ## Evaluation order and temporaries
//!
//! The source is read where it is written, and it can be written in two positions:
//!
//! - **Last, `..rest`**: like native struct update syntax, explicit fields are evaluated in
//!   written order, and the remaining fields are read from the source afterwards.
//! - **First, `rest..`**: the source is read first, the remaining fields are extracted from it,
//!   and the explicit fields are evaluated afterwards, in written order.
//!
//! `refield!` distinguishes two kinds of source expressions:
//!
//! - **Place expressions** are a bare identifier, a field access chain, a dereference, or a
//!   parenthesized place: `raw`, `inner.raw`, `*boxed`, `(*boxed)`. They are not bound to a
//!   temporary; each automatic field is read directly as `(place).field`, preserving partial-move
//!   semantics. A custom `Deref` wrapper used this way is dereferenced once per field; see
//!   [Custom `Deref` wrappers](#custom-deref-wrappers) for the single-evaluation form.
//! - **Value expressions** are everything else: `make_raw()`, `Raw { .. }`, `Default::default()`,
//!   and any cast such as `&wrapper as &Raw`. They are evaluated exactly once into a hygienic
//!   local before every field, the remaining fields are moved out of it, and whatever is left of
//!   it is dropped at the end of the `refield!` expression.
//!
//! A value is evaluated before every field, so it is written first whenever fields are written.
//! Without written fields there is nothing to evaluate before it, and `{ ..make_raw() }` reads it
//! exactly like `{ make_raw().. }`.
//!
//! ```rust
//! use core::cell::RefCell;
//! use std::rc::Rc;
//! use refield::{Refield, refield};
//!
//! struct Guard(Rc<RefCell<Vec<&'static str>>>);
//! impl Drop for Guard {
//!     fn drop(&mut self) {
//!         self.0.borrow_mut().push("drop rest");
//!     }
//! }
//!
//! struct Raw {
//!     a: i32,
//!     b: i32,
//!     guard: Guard,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Target {
//!     a: i32,
//!     b: i32,
//! }
//!
//! let log = Rc::new(RefCell::new(Vec::new()));
//! let make_raw = || {
//!     log.borrow_mut().push("rest");
//!     Raw { a: 1, b: 2, guard: Guard(log.clone()) }
//! };
//! let target = refield!(Target {
//!     make_raw()..,
//!     a: {
//!         log.borrow_mut().push("explicit a");
//!         10
//!     },
//! });
//! log.borrow_mut().push("after");
//!
//! assert_eq!(target, Target { a: 10, b: 2 });
//! assert_eq!(
//!     *log.borrow(),
//!     ["rest", "explicit a", "drop rest", "after"],
//! );
//! ```
//!
//! A value written after explicit fields is rejected, because it would have to be evaluated after
//! them yet be bound before the automatic fields read it. Write it first, or bind it to a local
//! and spread the local:
//!
//! ```compile_fail
//! use refield::{Refield, refield};
//! # struct Raw { a: i32, b: i32 }
//! # fn make_raw() -> Raw { Raw { a: 1, b: 2 } }
//! #[derive(Refield)]
//! struct Target { a: i32, b: i32 }
//!
//! // error: a value source cannot follow written fields
//! let target = refield!(Target { a: 10, ..make_raw() });
//! ```
//!
//! A place can be written in either position. Written last, it stays available to the explicit
//! fields until they have all been evaluated; written first, the automatic fields are moved out
//! of it before the explicit fields run, so those may only use the fields that are left:
//!
//! ```compile_fail,E0382
//! use refield::{Refield, refield};
//! struct Raw { a: String, b: String }
//! #[derive(Refield)]
//! struct Target { a: String, b: usize }
//!
//! let raw = Raw { a: "a".into(), b: "b".into() };
//! // `raw.a` has already been moved into `Target::a` when `b` is evaluated.
//! let target = refield!(Target { raw.., b: raw.a.len() });
//! ```
//!
//! A value expression is evaluated even when every field is overridden; this keeps the order and
//! the side effects of the written code unchanged. A place expression is also evaluated, but it is
//! only *used*, never moved as a whole.
//!
//! Explicit fields are emitted verbatim into the final struct literal, so they behave exactly as in
//! a native struct literal in every source position: they are coercion sites with the field's
//! expected type, their attributes apply only to them, and their temporaries are extended or
//! dropped at the end of the enclosing statement as usual:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { id: u32, name: &'static str }
//!
//! #[derive(Refield)]
//! struct Target<'a> { id: u32, name: &'a str }
//!
//! let make_raw = || Raw { id: 1, name: "raw" };
//! // The temporary `String` lives as long as `target`, as it would natively.
//! let target = refield!(Target { make_raw().., name: &String::from("written") });
//! assert_eq!((target.id, target.name), (1, "written"));
//! ```
//!
//! Because place expressions read fields directly, they support partial moves through references
//! and boxes:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Source { a: i32, b: i32 }
//! struct Holder { raw: Source }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Target { a: i32, b: i32 }
//!
//! let holder = Holder { raw: Source { a: 1, b: 2 } };
//! let target = refield!(Target { a: 10, ..holder.raw });
//! assert_eq!(target, Target { a: 10, b: 2 });
//!
//! let boxed = Box::new(Source { a: 3, b: 4 });
//! let target = refield!(Target { a: boxed.a + 10, ..*boxed });
//! assert_eq!(target, Target { a: 13, b: 4 });
//! ```
//!
//! ### Custom `Deref` wrappers
//!
//! Place expressions are projected **per field**: `..holder.raw` reads `holder.raw.a` and then
//! `holder.raw.b`, and `..*boxed` reads `(*boxed).a` and `(*boxed).b`. That is exactly what
//! permits partial moves and moving non-`Copy` fields out of a `Box`. For a wrapper whose
//! `Deref` implementation is not a pure accessor, however, re-projecting means re-running
//! `Deref::deref` for every field — and a `Deref` that alternates between targets would mix
//! fields from different values.
//!
//! Pin the final reference once with `..&wrapper as &Raw`, or `&wrapper as &Raw..` when fields
//! are written: the cast is a value expression. It requests `&Raw`, so Rust's deref coercion walks
//! `Outer -> Inner -> Raw` a single time before the fields are read, and every automatic field
//! comes from that one `&Raw`. A factory call works the same way, because Rust extends the
//! temporary's lifetime through the cast to the end of the expansion:
//!
//! ```rust
//! use core::cell::Cell;
//! use std::ops::Deref;
//! use refield::{Refield, refield};
//!
//! struct Raw { a: i32, b: i32 }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Target { a: i32, b: i32 }
//!
//! // A wrapper whose `Deref` alternates between two `Raw` values.
//! struct Alternating {
//!     first: Raw,
//!     second: Raw,
//!     calls: Cell<usize>,
//! }
//!
//! impl Deref for Alternating {
//!     type Target = Raw;
//!
//!     fn deref(&self) -> &Raw {
//!         let call = self.calls.get() + 1;
//!         self.calls.set(call);
//!         if call == 1 { &self.first } else { &self.second }
//!     }
//! }
//!
//! let wrapper = Alternating {
//!     first: Raw { a: 1, b: 10 },
//!     second: Raw { a: 2, b: 20 },
//!     calls: Cell::new(0),
//! };
//!
//! // Without `as &Raw` the fields are read through separate derefs: `(1, 20)`.
//! let mixed = refield!(Target { ..*wrapper });
//! assert_eq!(mixed, Target { a: 1, b: 20 });
//!
//! // With `as &Raw` the reference is pinned: `(1, 10)`.
//! let wrapper = Alternating {
//!     first: Raw { a: 1, b: 10 },
//!     second: Raw { a: 2, b: 20 },
//!     calls: Cell::new(0),
//! };
//! let pinned = refield!(Target { ..&wrapper as &Raw });
//! assert_eq!(pinned, Target { a: 1, b: 10 });
//!
//! // A temporary from a factory stays alive for the whole expansion.
//! let pinned = refield!(Target { ..&Alternating {
//!     first: Raw { a: 3, b: 30 },
//!     second: Raw { a: 4, b: 40 },
//!     calls: Cell::new(0),
//! } as &Raw });
//! assert_eq!(pinned, Target { a: 3, b: 30 });
//! ```
//!
//! The explicit cast is not implied by `..wrapper`, by `..*wrapper`, or by binding the factory
//! result to a local of the wrapper type: all three still expand to per-field projections.
//! `&*wrapper` strips only one layer and does not guarantee that the resulting reference already
//! targets the field source. Use the plain place form when you need to *move* non-`Copy` fields
//! out of the source; the shared-reference form can only copy or clone them.
//!
//! `..rest` must be the last element, and no comma may follow it. `rest..` must be the first
//! entry, after an optional `@profile` selector, and a comma separates it from the fields.
//!
//! ### Nested `refield!` and cross-layer partial moves
//!
//! `refield!` is an ordinary expression, so it nests: an inner call may consume one field of the
//! outer `raw` while the outer call keeps moving the remaining fields. Because the inner call is
//! itself a place-based expansion, it can partial-move out of `raw.inner`, leaving the rest of
//! `raw` available for the outer spread:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct InnerRaw { value: i32, label: &'static str }
//! struct OuterRaw { name: String, inner: InnerRaw, count: u32 }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Inner {
//!     value: i32,
//!     #[refield(with = |s: &'static str| s.into())]
//!     label: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Outer {
//!     name: String,
//!     inner: Inner,
//!     count: u32,
//! }
//!
//! let raw = OuterRaw {
//!     name: "outer".into(),
//!     inner: InnerRaw { value: 1, label: "inner" },
//!     count: 2,
//! };
//! let outer = refield!(Outer {
//!     // The inner expansion consumes `raw.inner` field by field...
//!     inner: refield!(Inner {
//!         value: raw.inner.value + 10,
//!         ..raw.inner
//!     }),
//!     // ...while the outer expansion still moves `raw.name` and `raw.count`.
//!     ..raw
//! });
//! assert_eq!(outer, Outer {
//!     name: "outer".into(),
//!     inner: Inner { value: 11, label: "inner".into() },
//!     count: 2,
//! });
//! ```
//!
//! ## Struct shapes
//!
//! Named structs, tuple structs, and unit structs are all supported. Tuple fields are written with
//! their index and may be mapped by name in both directions:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Named { x: i32, y: i32 }
//! struct Tuple(i32, i32);
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct FromNamed(#[refield(name = "x")] i32, #[refield(name = "y")] i32);
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct FromTuple {
//!     #[refield(name = "0")]
//!     x: i32,
//!     #[refield(name = "1")]
//!     y: i32,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Unit;
//!
//! let from_named = refield!(FromNamed { ..Named { x: 1, y: 2 } });
//! assert_eq!(from_named, FromNamed(1, 2));
//!
//! let from_tuple = refield!(FromTuple { ..Tuple(3, 4) });
//! assert_eq!(from_tuple, FromTuple { x: 3, y: 4 });
//!
//! // Tuple fields are addressed by index in the body.
//! let named = Named { x: 1, y: 2 };
//! let from_named = refield!(FromNamed { 0: 10, ..named });
//! assert_eq!(from_named, FromNamed(10, 2));
//!
//! // A unit target needs no fields at all.
//! assert_eq!(refield!(Unit {}), Unit);
//! assert_eq!(refield!(Unit { ..Named { x: 1, y: 2 } }), Unit);
//! assert_eq!(Unit! {}, Unit);
//! ```
//!
//! ## Generics, aliases, and `Self`
//!
//! Generic arguments may be written as `Type<Args>` or `Type::<Args>`:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     first: i64,
//!     raw_second: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Model<T, U> {
//!     first: T,
//!     #[refield(name = "raw_{}")]
//!     second: U,
//! }
//!
//! let model = refield!(Model::<i64, String> { ..Raw { first: 7, raw_second: "x".into() } });
//! assert_eq!(model, Model { first: 7, second: "x".into() });
//!
//! let model = refield!(Model<i64, String> { ..Raw { first: 8, raw_second: "y".into() } });
//! assert_eq!(model, Model { first: 8, second: "y".into() });
//! ```
//!
//! [`#[refieldable]`](refieldable) on a `type` alias generates a companion macro under the alias's
//! name. The alias may be generic, and aliases may chain:
//!
//! ```rust
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw {
//!     first: i64,
//!     raw_second: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Model<T, U> {
//!     first: T,
//!     #[refield(name = "raw_{}")]
//!     second: U,
//! }
//!
//! #[refieldable]
//! type Specialized<T> = Model<T, String>;
//!
//! #[refieldable]
//! type Chained = Specialized<i64>;
//!
//! fn main() {
//!     let model = refield!(Specialized::<i64> { ..Raw { first: 1, raw_second: "a".into() } });
//!     assert_eq!(model, Model { first: 1, second: "a".into() });
//!
//!     let model = refield!(Chained { ..Raw { first: 2, raw_second: "b".into() } });
//!     assert_eq!(model, Model { first: 2, second: "b".into() });
//!
//!     let model = Chained! { ..Raw { first: 3, raw_second: "c".into() } };
//!     assert_eq!(model, Model { first: 3, second: "c".into() });
//! }
//! ```
//!
//! An alias that was **not** annotated can still be constructed by naming the schema after `as`:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     first: i64,
//!     raw_second: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Model<T, U> {
//!     first: T,
//!     #[refield(name = "raw_{}")]
//!     second: U,
//! }
//!
//! type Plain = Model<i64, String>;
//!
//! fn main() {
//!     let model = refield!(Plain as Model { ..Raw { first: 9, raw_second: "z".into() } });
//!     assert_eq!(model, Model { first: 9, second: "z".into() });
//! }
//! ```
//!
//! [`#[refieldable]`](refieldable) on an `impl` block lets `refield!(Self { ... })` infer the
//! concrete schema from the implementation's self type:
//!
//! ```rust
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw<T> {
//!     first: T,
//!     raw_second: String,
//! }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct Model<T, U> {
//!     first: T,
//!     #[refield(name = "raw_{}")]
//!     second: U,
//! }
//!
//! #[refieldable]
//! impl<T: From<u8>> From<Raw<T>> for Model<T, String> {
//!     fn from(raw: Raw<T>) -> Self {
//!         // `refield!(Self { ... })` resolves to `Model`.
//!         let base = refield!(Self {
//!             first: T::from(10),
//!             ..raw
//!         });
//!         refield!(Self {
//!             first: base.first,
//!             second: base.second,
//!         })
//!     }
//! }
//!
//! fn main() {
//!     let model = Model::<u16, String>::from(Raw { first: 1, raw_second: "x".into() });
//!     assert_eq!(model, Model { first: 10, second: "x".into() });
//! }
//! ```
//!
//! `refield!(Self { ... })` is routed through a `__refield_ctx__` macro that only an
//! [`#[refieldable]`](refieldable) `impl` block defines. A `#[derive(Refield)]` does **not**
//! define one: redefining the same `macro_rules!` name in every module that derives would shadow
//! the enclosing `impl` context, so `refield!(Self { ... })` would stop resolving as soon as a
//! method body declared its own derived struct.
//!
//! Outside an annotated `impl` block the context macro is therefore not in scope, and the
//! invocation fails to resolve it:
//!
//! ```compile_fail
//! use refield::{Refield, refield};
//! #[derive(Refield)]
//! struct Target { value: u8 }
//! fn build(raw: Target) -> Target {
//!     refield!(Self { ..raw })
//! }
//! ```
//!
//! Inside an `impl` block that is **not** annotated with [`#[refieldable]`](refieldable), `Self`
//! names the implementing type but there is still no context macro for it, so the invocation fails
//! the same way:
//!
//! ```compile_fail
//! use refield::{Refield, refield};
//! #[derive(Refield)]
//! struct Target { value: u8 }
//! impl Target {
//!     fn build(raw: Target) -> Self {
//!         refield!(Self { ..raw })
//!     }
//! }
//! ```
//!
//! Annotate the `impl` block with [`#[refieldable]`](refieldable), or write the concrete type name,
//! to resolve the schema.
//!
//! ## Associated types
//!
//! An associated type does not name a companion macro by itself, but its schema can be named
//! explicitly after `as`, or resolved from an annotated `impl` block. This covers every associated
//! type that Rust itself can turn into a struct literal.
//!
//! Naming the schema after `as` works anywhere, including generic functions constrained by an
//! associated type equality:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! struct Raw { port: u16, host: String }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct ServiceConfig {
//!     port: u16,
//!     host: String,
//! }
//!
//! trait Service { type Config; }
//! struct Concrete;
//! impl Service for Concrete { type Config = ServiceConfig; }
//!
//! fn build<T: Service<Config = ServiceConfig>>(raw: Raw) -> T::Config {
//!     refield!(<T as Service>::Config as ServiceConfig { port: raw.port + 1, ..raw })
//! }
//!
//! let config = build::<Concrete>(Raw { port: 80, host: "localhost".into() });
//! assert_eq!(config, ServiceConfig { port: 81, host: "localhost".into() });
//! ```
//!
//! On an [`#[refieldable]`](refieldable) `impl` block, the associated types defined in the same
//! block are collected, so `refield!(Self::Assoc { ... })` and `refield!(<Self as Trait>::Assoc { ... })`
//! both resolve without an explicit `as`:
//!
//! ```rust
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw { port: u16, host: String }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct ServiceConfig {
//!     port: u16,
//!     host: String,
//! }
//!
//! trait Service {
//!     type Config;
//!     fn build(raw: Raw) -> Self::Config;
//! }
//!
//! struct Concrete;
//!
//! #[refieldable]
//! impl Service for Concrete {
//!     type Config = ServiceConfig;
//!
//!     fn build(raw: Raw) -> Self::Config {
//!         let base = refield!(Self::Config { port: raw.port + 1, ..raw });
//!         let qualified = refield!(<Self as Service>::Config { ..base });
//!         refield!(Self::Config { port: qualified.port + 1, ..qualified })
//!     }
//! }
//!
//! let config = Concrete::build(Raw { port: 80, host: "localhost".into() });
//! assert_eq!(config, ServiceConfig { port: 82, host: "localhost".into() });
//! ```
//!
//! ### Lexical resolution and schema identity
//!
//! `#[refieldable]` defines a hidden `macro_rules!` context inside an anonymous `const` wrapping
//! the block. `refield!` expands at its own location and emits an **unqualified** call to that
//! macro, so resolution is lexical: the nearest enclosing annotated `impl` wins, and the method
//! body is never scanned or rewritten. This keeps `refield!` transparent to other macros
//! (`stringify!` sees exactly what was written) and lets an inner annotated `impl` override an
//! outer one.
//!
//! The context only offers *candidate* schemas. Associated types are matched by name alone, not
//! by the trait's spelling, so a renamed import works without any special handling:
//!
//! ```rust
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw { port: u16 }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct ServiceConfig { port: u16 }
//!
//! trait Service { type Config; fn build(raw: Raw) -> Self::Config; }
//! struct Concrete;
//!
//! use Service as RenamedService;
//!
//! #[refieldable]
//! impl RenamedService for Concrete {
//!     type Config = ServiceConfig;
//!
//!     fn build(raw: Raw) -> Self::Config {
//!         // Written with the renamed import; no `as ServiceConfig` needed.
//!         refield!(<Self as RenamedService>::Config { port: raw.port + 1, ..raw })
//!     }
//! }
//!
//! assert_eq!(Concrete::build(Raw { port: 1 }), ServiceConfig { port: 2 });
//! ```
//!
//! What the candidate cannot do is silently construct a *different* type. Every schema carries a
//! unique identity method on the type it was derived for, and the constructed value is passed
//! through the method of the **requested** type. If the block implements two traits with an
//! associated type of the same name, naming one of them without `as` selects the same candidate,
//! and the identity check then rejects it when the actual requested type is the other one:
//!
//! ```compile_fail
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw { port: u16 }
//!
//! #[derive(Refield)]
//! struct FirstConfig { port: u16 }
//!
//! #[derive(Refield)]
//! struct SecondConfig { port: u16 }
//!
//! trait TraitOne { type Output; fn build(raw: Raw) -> Self::Output; }
//! trait TraitTwo { type Output; }
//!
//! struct Concrete;
//!
//! #[refieldable]
//! impl TraitOne for Concrete {
//!     type Output = FirstConfig;
//!
//!     fn build(raw: Raw) -> Self::Output {
//!         // `TraitTwo::Output` is `SecondConfig`, not the block's `Output`.
//!         // The candidate schema is `FirstConfig`, so the identity check on
//!         // `<Self as TraitTwo>::Output` fails; write
//!         // `<Self as TraitTwo>::Output as SecondConfig` instead.
//!         refield!(<Self as TraitTwo>::Output { ..raw })
//!     }
//! }
//!
//! impl TraitTwo for Concrete { type Output = SecondConfig; }
//! ```
//!
//! The same check rejects a mismatched explicit schema, so a candidate is either confirmed by the
//! type system or turned into a compile error — never applied silently to the wrong type.
//!
//! The lexical context applies to the whole method body, including nested unannotated `impl`
//! blocks. That is deliberate: §3.3 of the review requires an inherited candidate to be *checked*
//! rather than rejected outright, so an unannotated `impl Trait for Outer` nested in a
//! `#[refieldable] impl Outer` still works while `Self` is `Outer`. When the nested block's `Self`
//! names a different type, `refield!(Self { ... })` requests a schema identity from that type, and
//! the identity method only exists on the type the schema was derived for:
//!
//! ```compile_fail,E0599
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw { value: u8 }
//!
//! #[derive(Refield)]
//! struct Outer { value: u8 }
//!
//! #[derive(Refield)]
//! struct Other { value: u8 }
//!
//! #[refieldable]
//! impl Outer {
//!     fn build(raw: Raw) -> u8 {
//!         // An unannotated nested `impl` inherits the enclosing context, so
//!         // this `Self` resolves to the candidate schema of `Outer`. `Self`
//!         // here is `Other`, which does not own `Outer`'s schema identity
//!         // method `__refield_check_Outer_...`, so the request is rejected.
//!         #[allow(non_local_definitions)]
//!         impl Other {
//!             fn make(raw: Raw) -> Self {
//!                 refield!(Self { ..raw })
//!             }
//!         }
//!
//!         let _ = Other::make(raw);
//!         Outer { value: 0 }.value
//!     }
//! }
//! ```
//!
//! Annotate the nested block with `#[refieldable]` when it needs its own schema; the nearest
//! annotated `impl` then wins over the inherited candidate.
//!
//! The block's `Self` type does not have to be a nominal struct; defining associated types is
//! enough, so `impl Trait for ()` works the same way. Generic associated types use the usual
//! turbofish: `refield!(Self::Item::<u8> { ..raw })`.
//!
//! Finally, `#[refieldable(as = Schema)]` binds an alias to an associated type once, so callers do
//! not repeat the schema:
//!
//! ```rust
//! use refield::{Refield, refield, refieldable};
//!
//! struct Raw { port: u16, host: String }
//!
//! #[derive(Refield, Debug, PartialEq)]
//! struct ServiceConfig {
//!     port: u16,
//!     host: String,
//! }
//!
//! trait Service { type Config; }
//! struct Concrete;
//! impl Service for Concrete { type Config = ServiceConfig; }
//!
//! #[refieldable(as = ServiceConfig)]
//! type MyConfig = <Concrete as Service>::Config;
//!
//! fn main() {
//!     let raw = Raw { port: 0, host: "a".into() };
//!     let config = refield!(MyConfig { port: 80, ..raw });
//!     assert_eq!(config, ServiceConfig { port: 80, host: "a".into() });
//!
//!     let config = MyConfig! { ..Raw { port: 443, host: "b".into() } };
//!     assert_eq!(config, ServiceConfig { port: 443, host: "b".into() });
//! }
//! ```
//!
//! `as = ...` is rejected on structs and `impl` blocks:
//!
//! ```compile_fail
//! use refield::refieldable;
//! #[refieldable(as = Other)]
//! struct Target { value: u8 }
//! ```
//!
//! ## Visibility, exports, and crate paths
//!
//! The companion macro inherits the struct's visibility and lives next to it. A private struct can
//! be constructed from its module and descendants through a path:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! mod schema {
//!     use refield::{Refield, refield};
//!
//!     #[derive(Refield)]
//!     struct Private {
//!         port: u16,
//!     }
//!
//!     pub fn build(raw: Raw) -> u16 {
//!         refield!(Private { ..raw }).port
//!     }
//!
//!     pub struct Raw { pub port: u16 }
//! }
//!
//! assert_eq!(schema::build(schema::Raw { port: 8080 }), 8080);
//! ```
//!
//! A `pub` struct exports its companion macro to the crate root and re-exports it under the
//! struct's name, so ordinary `use` and `pub use` statements carry both the type and the macro:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! mod model {
//!     use refield::Refield;
//!
//!     #[derive(Refield, Debug, PartialEq)]
//!     pub struct Config {
//!         pub port: u16,
//!     }
//! }
//!
//! mod exports {
//!     pub use crate::model::Config;
//! }
//!
//! use exports::Config;
//!
//! fn main() {
//!     let config = Config! { ..model::Config { port: 8080 } };
//!     assert_eq!(config, model::Config { port: 8080 });
//!
//!     let config = refield!(Config { ..model::Config { port: 9090 } });
//!     assert_eq!(config.port, 9090);
//! }
//! ```
//!
//! When `refield` is renamed in `Cargo.toml`, or reached through a re-export, pass the path with
//! `crate = ...` on the struct-level attribute:
//!
//! ```rust
//! use refield as patches;
//!
//! struct Raw { port: u16 }
//!
//! #[derive(patches::Refield, Debug, PartialEq)]
//! #[refield(crate = patches)]
//! struct Config {
//!     port: u16,
//! }
//!
//! let config = patches::refield!(Config { ..Raw { port: 8080 } });
//! assert_eq!(config, Config { port: 8080 });
//! ```
//!
//! The annotation's `crate` path is evaluated where the struct is defined. A
//! `refield!` call expands with the runtime path of *its own* compilation when
//! that compilation has a `refield` dependency entry, so a locally scoped
//! alias used in `crate = ...` never has to be visible at call sites:
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! mod models {
//!     use refield as patches;
//!
//!     #[derive(patches::Refield, Debug, PartialEq)]
//!     #[refield(crate = patches)]
//!     pub struct Target { pub value: u8 }
//! }
//!
//! // `patches` is not in scope here.
//! let target = refield!(models::Target { value: 1 });
//! assert_eq!(target, models::Target { value: 1 });
//! ```
//!
//! A crate that reaches `refield!` only through a facade re-export has no
//! direct dependency entry to resolve, so it uses the definition site's
//! `crate = ...` path instead. Give the facade a `crate = ...` argument that
//! names the facade.
//!
//! ## Limitations
//!
//! The direct companion-macro spelling requires `Target` to be visible under its original name at
//! the call site. Renaming the import with `use ... as Alias` renames the macro too, but the macro
//! body still constructs the original struct name:
//!
//! ```compile_fail,E0422
//! mod model {
//!     use refield::Refield;
//!
//!     #[derive(Refield)]
//!     pub struct Target {
//!         pub port: u16,
//!     }
//! }
//!
//! use model::Target as Alias;
//!
//! fn main() {
//!     let raw = model::Target { port: 8080 };
//!     let _ = Alias! { ..raw };
//! }
//! ```
//!
//! Use [`refield!`] instead: it carries the path written at the call site, so renamed imports work.
//!
//! ```rust
//! use refield::{Refield, refield};
//!
//! mod model {
//!     use refield::Refield;
//!
//!     #[derive(Refield, Debug, PartialEq)]
//!     pub struct Target {
//!         pub port: u16,
//!     }
//! }
//!
//! use model::Target as Alias;
//!
//! let raw = model::Target { port: 8080 };
//! let target = refield!(Alias { ..raw });
//! assert_eq!(target, model::Target { port: 8080 });
//! ```
//!
//! `#[refieldable] type` aliases capture the target's schema at the alias definition site, so they
//! may be declared in nested modules, imported under another name, and chained: the target only
//! needs to be reachable from the alias's own module, and the alias's companion macro constructs
//! the alias itself, preserving its generic specialization.
//!
//! The schema is tied to the type it was derived for. Naming a different type after `as` is
//! rejected at compile time, even when both types have identical fields:
//!
//! ```compile_fail
//! use refield::{Refield, refield};
//!
//! struct Raw {
//!     value: u8,
//! }
//!
//! #[derive(Refield)]
//! struct WrongTarget {
//!     value: u8,
//! }
//!
//! #[derive(Refield)]
//! struct OtherTarget {
//!     value: u8,
//! }
//!
//! // `OtherTarget`'s schema does not describe `WrongTarget`: the generated
//! // schema identity check only exists on `OtherTarget`.
//! let target = refield!(WrongTarget as OtherTarget { ..Raw { value: 1 } });
//! ```
//!
//! `refield!` cannot construct an associated type from an unnormalized generic parameter, because
//! there is no nominal path to look up a companion macro for it and Rust rejects struct literals for
//! associated types in expression position (even natively). Name the schema after `as`, or annotate
//! the enclosing `impl` block — see [Associated types](#associated-types):
//!
//! ```compile_fail
//! trait Trait { type Assoc; }
//! fn build<T: Trait>(raw: T::Assoc) -> T::Assoc {
//!     refield::refield!(<T as Trait>::Assoc { ..raw })
//! }
//! ```
//!
//! The derive accepts structs only:
//!
//! ```compile_fail
//! use refield::Refield;
//! #[derive(Refield)]
//! enum Kind {
//!     A,
//! }
//! ```
//!
//! `..rest` must be last and must not be followed by a comma, and `rest..` must be first. The
//! target must contain every field that is neither explicit nor defaulted:
//!
//! ```compile_fail,E0063
//! use refield::{Refield, refield};
//! #[derive(Refield)]
//! struct Target {
//!     a: u8,
//!     b: u8,
//! }
//! let target = refield!(Target { a: 1 });
//! ```
//!
//! ## Compatibility
//!
//! The runtime crate is `#![no_std]`; generated code refers only to `core` and to the `refield`
//! crate's hidden support module. It works on stable Rust, from both edition 2021 and
//! edition 2024 crates.
//!
//! [`refield!`] supports every struct shape above in `const` contexts, as long as the conversion
//! expressions themselves are `const`.

#![no_std]

extern crate self as refield;

/// Derives the companion macro that implements [`refield!`] for this struct.
///
/// The generated macro is a `macro_rules!` item named after the struct (in the macro namespace),
/// with the struct's visibility. It accepts the same body as [`refield!`]:
///
/// ```rust
/// use refield::Refield;
///
/// struct Raw { port: u16 }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct Config { port: u16 }
///
/// let config = Config! { ..Raw { port: 8080 } };
/// assert_eq!(config, Config { port: 8080 });
/// ```
///
/// ## Struct-level attributes
///
/// Struct-level defaults apply to every automatic field; a field-level `name`, `with`, or
/// `skip` overrides them for that field.
///
/// - `#[refield(name = "...")]`: reads every automatic field from a differently named source.
///   `{}` expands to each target field's name, so one pattern covers a whole struct.
/// - `#[refield(with = value)]`: converts every automatic field. `value` is a pseudo-closure
///   shorthand for a helper method (`|pattern: Type| body`); use a typed parameter
///   (e.g. `|x: SrcType| ...`) when source types differ from field types.
/// - `#[refield(const)]`: generates the custom `with` / `default` helpers as `const fn`, so the
///   whole `refield!` call can run in a `const` context. Literal defaults are already `const fn`
///   without the flag.
/// - `#[refield(crate = path)]`: uses `path` instead of `::refield` for generated support paths.
///   Needed when the crate is renamed or re-exported.
///
/// ## Field-level attributes
///
/// - `#[refield(name = "...")]`: reads the automatic value from a differently named source field.
///   `{}` expands to the target field's name; numeric names select tuple fields and vice versa.
/// - `#[refield(with = value)]`: converts this automatic field. The value is a
///   pseudo-closure shorthand for a helper method (`|pattern: Type| body`),
///   and may also be written as a string (`with = "|x| ..."`).
///
///   The input type defaults to the target field's type, so homogeneous conversions need no
///   annotation: `#[refield(with = |x| x + 1)]`. A typed
///   pseudo-closure takes its input from its own parameter
///   (`#[refield(with = |s: &str| s.to_uppercase())]`). Bare function paths and modifiers such
///   as `async`, `move`, `const`, and `for<...>` are not part of this grammar and are syntax errors.
/// - `#[refield(default)]` / `#[refield(default = expr)]`: initializes the field when there is no
///   `..rest`, or when combined with `skip`.
/// - `#[refield(skip)]`: never reads the field from `..rest` and initializes it with
///   `Default::default()`. Combine with `default = expr` to choose the value. `skip` cannot be
///   combined with `name` or `with`.
/// - `#[refield(bound(T: Trait))]`: adds `where` predicates to the helper method generated for this
///   field's `with` or `default` expression, without constraining the struct itself. Parentheses
///   syntax `bound(...)` is required.
/// - `#[refield(const)]`: generates this field's helper as a `const fn`. Equivalent to the
///   struct-level flag, applied per field:
///   `#[refield(const, with = ...)]`, `#[refield(const, default = ...)]`.
/// - `#[refield(on(...))]`: declares an extra rule that applies only when the call selects that
///   profile with `@alt` as the first entry of the body (e.g. `#[refield(on(alt), name = "...")]`
///   or `#[refield(on(alt, legacy), ...)]`). Attributes without `on(...)` contribute to the default
///   rule. Multiple attributes for the same profile merge their configuration keys.
///
/// Attributes only affect automatic extraction; explicitly written fields bypass them.
///
/// ## Definition-site evaluation
///
/// Custom `with` conversions and `default = expr` expressions are not pasted into the call site.
/// They become inherent helper methods on the target struct, so they evaluate in its
/// **definition-site scope**: the struct's generic parameters and lifetimes are in scope, and so
/// are private functions, constants, and imports of the defining module. This is also why a
/// heterogeneous conversion needs a typed pseudo-closure parameter — the helper's parameter type
/// cannot be inferred from the call site's source type.
///
/// Applying the derive to anything other than a struct is an error.
pub use refield_macros::Refield;

/// Constructs a struct from an explicit field list and a cross-type `..rest` update.
///
/// ```rust
/// use refield::{Refield, refield};
///
/// struct Raw {
///     host: &'static str,
///     port: u16,
/// }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct Config {
///     host: String,
///     port: u16,
/// }
///
/// let raw = Raw { host: "localhost", port: 8080 };
/// let config = refield!(Config { host: raw.host.to_owned(), ..raw });
/// assert_eq!(config, Config { host: "localhost".into(), port: 8080 });
/// ```
///
/// # Syntax
///
/// ```text
/// refield!(Target { field: value, shorthand, 0: value, ..rest })
/// refield!(Target { rest.., field: value, shorthand, 0: value })
/// refield!(Target::<Args> { ..rest })
/// refield!(Target { @alt field: value, ..rest })
/// refield!(Target { @alt rest.., field: value })
/// refield!(Alias as Schema { ..rest })
/// refield!(<T as Trait>::Assoc as Schema { ..rest })
/// ```
///
/// - `Target` is a nominal type path. Its companion macro is invoked at that path, so imports
///   renamed with `use ... as Alias` work here.
/// - `Alias as Schema` uses `Alias` for the constructed value and `Schema` (a path whose last
///   segment names a struct with a companion macro) for the field schema. This supports type
///   aliases that were not annotated with [`refieldable`].
/// - An associated type such as `<T as Trait>::Assoc` has no companion macro of its own, so it
///   needs an explicit `as Schema`, or must appear inside an [`#[refieldable]`](refieldable) `impl`
///   block that defines the associated type. See the crate documentation on associated types.
/// - Explicit fields may be written in any order. Tuple structs use numeric members such as `0:`.
/// - The source is optional and is read where it is written. `..rest` must be last, no comma may
///   follow it, and the explicit fields are evaluated before it, so they may refer to `rest`
///   before it is consumed. `rest..` must be first and is read before the explicit fields.
///
///   Either position accepts a place expression (`raw`, `inner.raw`, `*boxed`). A value expression
///   (`make_raw()`) is evaluated once, before every field, so it must be written first whenever
///   fields are written; `{ ..make_raw() }` alone is accepted. See the crate documentation for
///   the evaluation and temporary rules.
///
///   A custom `Deref` wrapper is expanded per field as a place, which would run `Deref::deref`
///   once per field. Write `&wrapper as &Raw..` (or `&make_wrapper() as &Raw..` for a temporary)
///   to pin the final `&Raw` once and read every field through it.
/// - `@alt` selects a profile declared with `#[refield(on(alt), ...)]`. It must be the first entry
///   of the body; the comma after it is optional (`{ @alt ..raw }`, `{ @alt, ..raw }`, and
///   `{ @alt raw.. }` all work). Fields without a rule for `alt` keep their default rule.
///
/// # Requirements
///
/// The companion macro must be in scope at `Target`'s path. `Target` itself must have been
/// annotated with `#[derive(Refield)]` or `#[refieldable]`, or be an alias annotated with
/// `#[refieldable]`, or be used with an explicit `as Schema`.
pub use refield_macros::refield;

/// Adds [`refield!`] support to a struct, a type alias, or an `impl` block.
///
/// On a struct this is equivalent to adding `#[derive(Refield)]` plus the given struct-level
/// arguments:
///
/// ```rust
/// use refield::{refieldable, refield};
///
/// struct Raw { port: u16 }
///
/// #[refieldable]
/// #[derive(Debug, PartialEq)]
/// struct Config { port: u16 }
///
/// let config = refield!(Config { ..Raw { port: 8080 } });
/// assert_eq!(config, Config { port: 8080 });
/// ```
///
/// Struct-level arguments are `name = "..."` (rename every automatic source; `{}` expands to the
/// field's name), `with = value` (conversion for every automatic field), `const` (generate every
/// custom `with` / `default` helper as a `const fn`), and `crate = path` (redirect generated
/// support paths). Field-level `#[refield(...)]` attributes work exactly as with the derive,
/// including `bound(...)` and `const`, and they override the struct-level defaults.
///
/// ```rust
/// use refield::{refieldable, refield};
///
/// struct Raw { raw_port: u16, raw_name: String }
///
/// #[refieldable(name = "raw_{}")]
/// #[derive(Debug, PartialEq)]
/// struct Config { port: u16, name: String }
///
/// let config = refield!(Config { ..Raw { raw_port: 8080, raw_name: "node".into() } });
/// assert_eq!(config, Config { port: 8080, name: "node".into() });
/// ```
///
/// On a `type` alias it generates a companion macro under the alias's name, so the alias can be
/// used with both `refield!(Alias { ... })` and `Alias! { ... }`. Aliases may be generic and may
/// alias other annotated aliases:
///
/// ```rust
/// use refield::{Refield, refield, refieldable};
///
/// struct Raw { port: u16 }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct Config { port: u16 }
///
/// #[refieldable]
/// type Alias = Config;
///
/// fn main() {
///     let config = refield!(Alias { ..Raw { port: 8080 } });
///     assert_eq!(config, Config { port: 8080 });
///     let config = Alias! { ..Raw { port: 9090 } };
///     assert_eq!(config, Config { port: 9090 });
/// }
/// ```
///
/// The alias captures the target's schema at its definition site, so it may be declared in nested
/// modules, imported under another name, and chained. The companion macro constructs the alias
/// itself, so the alias's generic specialization is preserved.
///
/// When the alias names an associated type there is no nominal struct path to forward to, so pass
/// the schema explicitly with `as`:
///
/// ```rust
/// use refield::{Refield, refield, refieldable};
///
/// struct Raw { port: u16 }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct Config { port: u16 }
///
/// trait Service { type Config; }
/// struct Concrete;
/// impl Service for Concrete { type Config = Config; }
///
/// #[refieldable(as = Config)]
/// type MyConfig = <Concrete as Service>::Config;
///
/// fn main() {
///     let config = refield!(MyConfig { ..Raw { port: 8080 } });
///     assert_eq!(config, Config { port: 8080 });
///     let config = MyConfig! { ..Raw { port: 9090 } };
///     assert_eq!(config, Config { port: 9090 });
/// }
/// ```
///
/// `as` is only valid on type aliases.
///
/// On an `impl` block it provides a context for `refield!(Self { ... })` inside the block's items,
/// resolving `Self` to the implementation's concrete type path. Associated types defined in the
/// same block are resolved as well, so `refield!(Self::Assoc { ... })` and
/// `refield!(<Self as Trait>::Assoc { ... })` reach the associated type's definition without an
/// explicit `as`:
///
/// ```rust
/// use refield::{Refield, refield, refieldable};
///
/// struct Raw { port: u16 }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct Config { port: u16 }
///
/// #[refieldable]
/// impl Config {
///     fn with_default_port(raw: Raw) -> Self {
///         refield!(Self { port: raw.port + 1, ..raw })
///     }
/// }
///
/// fn main() {
///     assert_eq!(
///         Config::with_default_port(Raw { port: 8080 }),
///         Config { port: 8081 },
///     );
/// }
/// ```
///
/// The block's self type must either be a nominal type path or the block must define associated
/// types with nominal paths; that is what allows `impl Trait for ()` to work.
///
/// ## How the `impl` context is resolved
///
/// The block is wrapped in an anonymous `const` that defines a hidden, lexically scoped
/// `__refield_ctx__` macro. Method bodies are left untouched: `refield!` expands where it is
/// written and emits an unqualified call to that macro, so the nearest enclosing annotated `impl`
/// provides the candidates and an inner annotated block overrides an outer one. No token scanning
/// happens, so other macros (including `stringify!`) still observe the original spelling.
///
/// Associated types are keyed by name only. The trait is not compared by spelling, so a renamed
/// import resolves like any other:
///
/// ```rust
/// use refield::{Refield, refield, refieldable};
///
/// struct Raw { port: u16 }
///
/// #[derive(Refield, Debug, PartialEq)]
/// struct ServiceConfig { port: u16 }
///
/// trait Service { type Config; fn build(raw: Raw) -> Self::Config; }
/// struct Concrete;
///
/// use Service as Renamed;
///
/// #[refieldable]
/// impl Renamed for Concrete {
///     type Config = ServiceConfig;
///
///     fn build(raw: Raw) -> Self::Config {
///         refield!(<Self as Renamed>::Config { port: raw.port + 1, ..raw })
///     }
/// }
///
/// assert_eq!(Concrete::build(Raw { port: 1 }), ServiceConfig { port: 2 });
/// ```
///
/// The candidate is only a proposal. Every schema carries a unique identity method defined on the
/// type it was derived for, and the constructed value is passed through the identity method of the
/// **requested** type. A request for an associated type from a different trait — or with the wrong
/// explicit `as Schema` — therefore fails to compile instead of silently using the candidate's
/// rules. Name the right schema with `as` to fix it:
/// `refield!(<Self as OtherTrait>::Output as OtherSchema { ... })`.
pub use refield_macros::refieldable;

/// Compile-fail checks that only `cargo test --doc` sees: each construction is
/// rejected with the same error as the equivalent native struct literal.
#[cfg(doctest)]
mod compile_fail_tests {
    /// A source that implements `Drop` cannot give up a non-`Copy` field:
    ///
    /// ```compile_fail,E0509
    /// use refield::{Refield, refield};
    /// struct Raw { a: String, b: String }
    /// impl Drop for Raw { fn drop(&mut self) {} }
    /// #[derive(Refield)]
    /// struct Target { a: String }
    /// let raw = Raw { a: String::new(), b: String::new() };
    /// let _ = refield!(Target { ..raw });
    /// ```
    struct MoveOutOfDropSource;

    /// A private field of the target cannot be filled from outside its module:
    ///
    /// ```compile_fail,E0451
    /// use refield::refield;
    /// mod model {
    ///     #[derive(refield::Refield)]
    ///     pub struct Target {
    ///         pub open: u8,
    ///         hidden: u8,
    ///     }
    /// }
    /// struct Raw { open: u8, hidden: u8 }
    /// let _ = refield!(model::Target { ..Raw { open: 1, hidden: 2 } });
    /// ```
    struct PrivateTargetField;

    /// A `#[non_exhaustive]` struct cannot be built outside its crate:
    ///
    /// ```compile_fail,E0639
    /// use refield::refield;
    /// struct Raw { port: u16 }
    /// let _ = refield!(refield_test_models::NonExhaustiveModel { ..Raw { port: 1 } });
    /// ```
    struct NonExhaustiveTarget;

    /// A written field the target does not have:
    ///
    /// ```compile_fail,E0560
    /// use refield::{Refield, refield};
    /// struct Raw { a: u8 }
    /// #[derive(Refield)]
    /// struct Target { a: u8 }
    /// let _ = refield!(Target { Raw { a: 1 }.., missing: 2 });
    /// ```
    struct UnknownWrittenField;

    /// A field written twice:
    ///
    /// ```compile_fail,E0062
    /// use refield::{Refield, refield};
    /// struct Raw { a: u8 }
    /// #[derive(Refield)]
    /// struct Target { a: u8 }
    /// let _ = refield!(Target { Raw { a: 1 }.., a: 2, a: 3 });
    /// ```
    struct DuplicateWrittenField;

    /// A written field of the wrong type:
    ///
    /// ```compile_fail,E0308
    /// use refield::{Refield, refield};
    /// struct Raw { a: u8 }
    /// #[derive(Refield)]
    /// struct Target { a: u8 }
    /// let _ = refield!(Target { Raw { a: 1 }.., a: "two" });
    /// ```
    struct MistypedWrittenField;
}

#[doc(hidden)]
pub mod __private {
    pub use refield_macros::{Prepare, alias, construct, discard};

    /// Rust 2021 braces for the whole expansion.
    ///
    /// A block's tail-expression temporary scope follows the edition of the
    /// block's own braces. These braces come from this Rust 2021 crate, so
    /// temporaries in the tail of a `refield!` expansion live to the end of
    /// the caller's statement, exactly as they would in a plain struct
    /// literal. Braces emitted by `refield-macros` would carry its edition.
    ///
    /// A construction is passed as `{ statements } { tail }`. Only the tail
    /// is exempt from `clippy::needless_update`, which its `..base` type tie
    /// always triggers; the statements, which evaluate the user's source,
    /// keep every lint the caller enables.
    #[doc(hidden)]
    #[macro_export]
    macro_rules! __refield_block {
        ({ $($statements:tt)* } { $($tail:tt)* }) => {{
            $($statements)*
            #[allow(clippy::needless_update)]
            {
                $($tail)*
            }
        }};
        ($($body:tt)*) => {{
            $($body)*
        }};
    }
    pub use crate::__refield_block as block;

    /// Names a value of any type in dead code, for type inference only.
    ///
    /// Only ever called inside `if false { .. }`; it is never evaluated.
    #[inline]
    pub const fn fake<T>() -> T {
        panic!("refield: internal placeholder evaluated")
    }

    /// Moves a value out of a local without running anything.
    ///
    /// Only ever called inside `if false { .. }` on the placeholder that ties
    /// the literal's type: moving it out means the local is never dropped, so
    /// a `const fn` construction needs no destructor for it.
    #[inline]
    pub const fn sink<T>(value: T) {
        ::core::mem::forget(value)
    }
}
